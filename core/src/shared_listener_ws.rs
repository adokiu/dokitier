//! Shared WebSocket (`ws://` / `wss://`) listeners.
//!
//! All network instances of one core process can share one public WebSocket
//! port per scheme. Every instance still binds its own private loopback
//! listener (for example `ws://127.0.0.1:33001`); this module owns the public
//! ports and forwards every fresh WebSocket connection to the right instance by
//! peeking at the first EasyTier packet on that connection.
//!
//! # Protocol matching
//!
//! After the HTTP `101 Switching Protocols` handshake the connecting EasyTier
//! peer sends its regular handshake packet as the first binary WebSocket
//! message. The message body is the tunnel payload of a [`ZCPacket`]
//! (`crates/dokitier-core/src/packet/mod.rs::ZCPacket::tunnel_payload_bytes`),
//! i.e. exactly the bytes that the built-in `tunnel::websocket` transport puts
//! into one WebSocket binary message:
//!
//! ```text
//! | PeerManagerHeader (PEER_MANAGER_HEADER_SIZE bytes) | payload |
//! ```
//!
//! This module therefore:
//!
//! 1. completes the server side WebSocket upgrade,
//! 2. waits for the first binary message (8s timeout, 64 KiB cap),
//! 3. decodes the `PeerManagerHeader` from the first bytes of that message and
//!    requires `packet_type == PacketType::HandShake`,
//! 4. prost-decodes the remaining bytes as
//!    `dokitier_proto::peer_rpc::HandshakeRequest` and reads `network_name`,
//! 5. calls `resolve(network_name)` to obtain the internal loopback port;
//!    `resolve` returning `None` means "no instance owns this network" and the
//!    connection is dropped,
//! 6. dials `ws://127.0.0.1:<port>`, replays the consumed first message to the
//!    instance listener and then relays every following binary/text message in
//!    both directions until either side closes.
//!
//! The network secret digest is deliberately *not* validated here: the
//! instance listener receives the replayed handshake and performs its normal
//! authentication (magic/version/secret check) exactly as if the peer had
//! connected to it directly.
//!
//! # wss / TLS
//!
//! `wss://` public addresses are terminated in this module. The TLS server
//! configuration is built with rustls using a freshly generated self-signed
//! certificate (SAN `localhost`, key generated by `rcgen`); this mirrors the
//! approach of the built-in `tunnel::websocket` transport, whose (`wss://`)
//! listener also uses a self-signed certificate. EasyTier's WebSocket client
//! skips certificate verification, so EasyTier peers can connect to such a
//! listener. There is currently no way to provide a custom certificate,
//! hostname or client authentication.
//!
//! # Known limitations
//!
//! * The upstream (loopback) hop is always plain `ws://127.0.0.1:<port>`. An
//!   instance listener that was rewritten to `wss://` would not be reachable
//!   through this module.
//! * Only the first message is inspected. Ping/pong control frames are handled
//!   by the WebSocket layer itself and are not proxied; a close frame ends the
//!   relay for that direction.
//! * The first message must be binary. Text or undecodable first messages cause
//!   the connection to be closed. `magic`, protocol version and secret digest
//!   are not checked here (the instance checks them).
//! * If `resolve` returns `None`, or the internal listener cannot be reached,
//!   the connection is closed and the problem is only logged (debug/warn); no
//!   HTTP error is returned to the client because the upgrade has already
//!   completed by then.
//! * Hot reload is caller-driven: abort the returned `JoinHandle`s and call
//!   [`bind`] again. A partially failed `bind` aborts the listeners it already
//!   spawned and returns `Err`, so the caller can restore the previous address
//!   set.
//! * No `Forwarded`/`X-Forwarded-For` handling: the internal instance listener
//!   sees `127.0.0.1` as the remote peer, which is the intended loopback
//!   rewrite.
//!
//! This module is compiled only when the `websocket` feature is enabled (it
//! needs `tokio-websockets`, `rustls`, `tokio-rustls`, `rcgen` and `http`,
//! which that feature already pulls in). Without the feature a stub [`bind`]
//! returning an error is provided so integration code can stay unconditional.

#[cfg(feature = "websocket")]
pub use imp::{NetworkResolver, bind};

#[cfg(not(feature = "websocket"))]
pub type NetworkResolver = std::sync::Arc<dyn Fn(&str) -> Option<u16> + Send + Sync>;

#[cfg(not(feature = "websocket"))]
pub async fn bind(
    _addrs: Vec<String>,
    _resolve: NetworkResolver,
) -> anyhow::Result<(Vec<String>, Vec<tokio::task::JoinHandle<()>>)> {
    anyhow::bail!("websocket shared listener requires the `websocket` feature")
}

#[cfg(feature = "websocket")]
mod imp {
    use std::net::SocketAddr;
    use std::sync::Arc;
    use std::time::Duration;

    use anyhow::{Context as _, anyhow};
    use bytes::{Bytes, BytesMut};
    use dokitier_core::packet::{PEER_MANAGER_HEADER_SIZE, PacketType, ZCPacket, ZCPacketType};
    use dokitier_proto::peer_rpc::HandshakeRequest;
    use futures::stream::{SplitSink, SplitStream};
    use futures::{SinkExt, StreamExt};
    use prost::Message as _;
    use tokio::io::{AsyncRead, AsyncWrite};
    use tokio::net::{TcpListener, TcpStream};
    use tokio_rustls::TlsAcceptor;
    use tokio_websockets::{ClientBuilder, Limits, Message, ServerBuilder, WebSocketStream};

    /// Maps an EasyTier network name to the loopback port of the instance
    /// listener that serves that network. Returning `None` means the network is
    /// unknown to this core.
    pub type NetworkResolver = Arc<dyn Fn(&str) -> Option<u16> + Send + Sync>;

    /// How long to wait for the EasyTier handshake after the WebSocket upgrade.
    const FIRST_MESSAGE_TIMEOUT: Duration = Duration::from_secs(8);
    /// How long to wait for the client's HTTP Upgrade request.
    const SERVER_HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(10);
    /// How long to wait for the TLS handshake of a `wss://` connection.
    const TLS_HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(10);
    /// How long to wait for the TCP connect to the loopback instance listener.
    const INTERNAL_CONNECT_TIMEOUT: Duration = Duration::from_secs(5);
    /// How long to wait for the internal WebSocket handshake.
    const INTERNAL_HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(10);
    /// Upper bound for the first (handshake) message, matching the TCP shared
    /// listener.
    const MAX_FIRST_MESSAGE: usize = 64 * 1024;

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    enum Scheme {
        Ws,
        Wss,
    }

    impl Scheme {
        fn as_str(self) -> &'static str {
            match self {
                Self::Ws => "ws",
                Self::Wss => "wss",
            }
        }
    }

    /// Binds every `ws://`/`wss://` address and starts one accept loop per
    /// bound address.
    ///
    /// `addrs` may contain bare `host:port` entries (treated as `ws://`) and
    /// entries with a `ws://` or `wss://` scheme. A `:0` port binds an
    /// ephemeral port; the returned strings always carry the scheme and the
    /// effective local address.
    ///
    /// If binding any address fails, the listeners spawned for earlier
    /// addresses are aborted and an error is returned, so the caller can keep
    /// the previous address set (rollback semantics for hot updates).
    ///
    /// # Errors
    ///
    /// Returns an error for unsupported schemes, malformed addresses, bind
    /// failures, and failures while building the `wss://` TLS configuration.
    pub async fn bind(
        addrs: Vec<String>,
        resolve: NetworkResolver,
    ) -> anyhow::Result<(Vec<String>, Vec<tokio::task::JoinHandle<()>>)> {
        let mut tasks: Vec<tokio::task::JoinHandle<()>> = Vec::new();
        let mut bound: Vec<String> = Vec::new();
        for raw in addrs {
            let addr = raw.trim();
            if addr.is_empty() {
                continue;
            }
            match bind_one(addr, &resolve, &mut tasks).await {
                Ok(bound_addr) => bound.push(bound_addr),
                Err(err) => {
                    for task in &tasks {
                        task.abort();
                    }
                    return Err(err);
                }
            }
        }
        Ok((bound, tasks))
    }

    async fn bind_one(
        addr: &str,
        resolve: &NetworkResolver,
        tasks: &mut Vec<tokio::task::JoinHandle<()>>,
    ) -> anyhow::Result<String> {
        let (scheme, authority) = parse_addr(addr)?;
        let listener = TcpListener::bind(&authority)
            .await
            .with_context(|| format!("bind shared websocket listener `{addr}`"))?;
        let local = listener
            .local_addr()
            .with_context(|| format!("query local address of shared websocket listener `{addr}`"))?;
        let tls = match scheme {
            Scheme::Ws => None,
            Scheme::Wss => Some(build_tls_acceptor()?),
        };
        tasks.push(tokio::spawn(accept_loop(listener, tls, resolve.clone())));
        let bound = format!("{}://{local}", scheme.as_str());
        tracing::info!(addr = %bound, "shared websocket listener bound");
        Ok(bound)
    }

    fn parse_addr(addr: &str) -> anyhow::Result<(Scheme, String)> {
        let (scheme, rest) = match addr.split_once("://") {
            Some((scheme, rest)) => (scheme, rest),
            None => ("ws", addr),
        };
        let scheme = match scheme.to_ascii_lowercase().as_str() {
            "ws" => Scheme::Ws,
            "wss" => Scheme::Wss,
            other => anyhow::bail!(
                "unsupported shared listener scheme `{other}` in `{addr}` (expected ws or wss)"
            ),
        };
        // Listener URLs may carry a path; only the authority part is bindable.
        let authority = rest.split('/').next().unwrap_or_default().trim();
        if authority.is_empty() {
            anyhow::bail!("shared websocket listener `{addr}` has no host:port");
        }
        Ok((scheme, authority.to_string()))
    }

    /// Builds the TLS server configuration for `wss://` listeners.
    ///
    /// A fresh self-signed certificate is generated at bind time. EasyTier's
    /// WebSocket client does not verify server certificates, so this is enough
    /// for peer traffic; it is not meant to be browsed by a normal TLS client.
    fn build_tls_acceptor() -> anyhow::Result<TlsAcceptor> {
        let certified = rcgen::generate_simple_self_signed(vec!["localhost".to_string()])
            .context("generate self-signed certificate for shared wss listener")?;
        let cert_der = certified.cert.der().clone();
        let key_der =
            rustls::pki_types::PrivatePkcs8KeyDer::from(certified.signing_key.serialize_der());
        let config =
            rustls::ServerConfig::builder_with_provider(Arc::new(rustls::crypto::ring::default_provider()))
                .with_safe_default_protocol_versions()
                .context("select TLS protocol versions for shared wss listener")?
                .with_no_client_auth()
                .with_single_cert(vec![cert_der], key_der.into())
                .context("build TLS server config for shared wss listener")?;
        Ok(TlsAcceptor::from(Arc::new(config)))
    }

    async fn accept_loop(listener: TcpListener, tls: Option<TlsAcceptor>, resolve: NetworkResolver) {
        loop {
            let (stream, peer) = match listener.accept().await {
                Ok(value) => value,
                Err(err) => {
                    tracing::warn!(?err, "shared websocket listener accept failed");
                    tokio::time::sleep(Duration::from_millis(200)).await;
                    continue;
                }
            };
            let _ = stream.set_nodelay(true);
            let tls = tls.clone();
            let resolve = resolve.clone();
            tokio::spawn(async move {
                let result = match tls {
                    Some(acceptor) => {
                        match tokio::time::timeout(TLS_HANDSHAKE_TIMEOUT, acceptor.accept(stream))
                            .await
                        {
                            Ok(Ok(stream)) => handle_session(stream, peer, false, resolve).await,
                            Ok(Err(err)) => Err(anyhow!("tls handshake failed: {err}")),
                            Err(_) => Err(anyhow!("tls handshake timed out")),
                        }
                    }
                    None => handle_session(stream, peer, true, resolve).await,
                };
                if let Err(err) = result {
                    tracing::debug!(%peer, error = %err, "shared websocket connection closed");
                }
            });
        }
    }

    async fn handle_session<S>(
        stream: S,
        peer: SocketAddr,
        plain_ws: bool,
        resolve: NetworkResolver,
    ) -> anyhow::Result<()>
    where
        S: AsyncRead + AsyncWrite + Unpin + Send + 'static,
    {
        let (request, mut client) = tokio::time::timeout(
            SERVER_HANDSHAKE_TIMEOUT,
            ServerBuilder::new()
                .limits(Limits::unlimited())
                .max_headers(128)
                .accept(stream),
        )
        .await
        .map_err(|_| anyhow!("websocket upgrade timed out"))?
        .context("websocket upgrade failed")?;
        let path = request.uri().path().to_owned();

        let first = tokio::time::timeout(FIRST_MESSAGE_TIMEOUT, read_first_binary(&mut client))
            .await
            .map_err(|_| anyhow!("timed out waiting for the first websocket message"))?
            .ok_or_else(|| anyhow!("websocket closed before the first handshake message"))?;

        let network = network_from_message(&first)
            .ok_or_else(|| anyhow!("first websocket message is not an EasyTier HandshakeRequest"))?;
        tracing::debug!(%peer, %path, %network, "shared websocket connection matched a network");

        if let Some(peer_manager) = crate::shared_listener_handoff::resolve_network(&network) {
            let local_url = url::Url::parse(&format!("ws://{peer}")).expect("valid ws url");
            let handoff_result = if plain_ws {
                // Plain ws: use the custom full-duplex data plane.
                let stream = client.into_inner();
                let first = ZCPacket::new_from_buf(
                    bytes::BytesMut::from(&first[..]),
                    dokitier_core::packet::ZCPacketType::DummyTunnel,
                );
                let tunnel = crate::tunnel::websocket::build_plain_ws_tunnel(
                    stream,
                    Some(first),
                    false,
                    crate::proto::common::TunnelInfo {
                        tunnel_type: "ws".to_owned(),
                        local_addr: Some(local_url.clone().into()),
                        remote_addr: None,
                        resolved_remote_addr: None,
                    },
                );
                peer_manager.add_tunnel_as_server(tunnel).await.map_err(anyhow::Error::from)
            } else {
                crate::shared_listener_handoff::handoff_ws(
                    &peer_manager,
                    client,
                    Bytes::from(first),
                    local_url,
                    None,
                )
                .await
            };
            match handoff_result {
                Ok(()) => return Ok(()),
                Err(err) => {
                    tracing::warn!(%network, error = %err, "shared websocket direct handoff failed");
                    return Ok(());
                }
            }
        }

        let port = resolve(&network)
            .ok_or_else(|| anyhow!("no local instance serves network `{network}`"))?;
        let mut upstream = connect_loopback(port)
            .await
            .with_context(|| format!("connect internal websocket listener for network `{network}`"))?;

        upstream
            .send(Message::binary(first))
            .await
            .context("replay first handshake message to the internal listener")?;

        let (client_sink, client_stream) = client.split();
        let (upstream_sink, upstream_stream) = upstream.split();
        tokio::select! {
            _ = pump(client_stream, upstream_sink, &network) => {}
            _ = pump(upstream_stream, client_sink, &network) => {}
        }
        Ok(())
    }

    /// Reads messages until the first binary one; ping/pong frames are consumed
    /// by the WebSocket layer and text frames are skipped because the EasyTier
    /// handshake is always binary.
    async fn read_first_binary<S>(client: &mut WebSocketStream<S>) -> Option<Bytes>
    where
        S: AsyncRead + AsyncWrite + Unpin,
    {
        loop {
            let message = match client.next().await {
                Some(Ok(message)) => message,
                Some(Err(err)) => {
                    tracing::debug!(?err, "shared websocket receive failed before the handshake");
                    return None;
                }
                None => return None,
            };
            if message.is_close() {
                return None;
            }
            if message.is_binary() {
                let payload = Bytes::from(message.into_payload());
                if payload.len() > MAX_FIRST_MESSAGE {
                    tracing::debug!(
                        len = payload.len(),
                        "shared websocket first message is too large"
                    );
                    return None;
                }
                return Some(payload);
            }
            if message.is_text() {
                tracing::debug!("skipping text frame before the EasyTier handshake");
            }
        }
    }

    /// Decodes the network name from the first WebSocket message, which is a
    /// [`ZCPacket`] tunnel payload (`PeerManagerHeader` + `HandshakeRequest`).
    fn network_from_message(message: &[u8]) -> Option<String> {
        if message.len() < PEER_MANAGER_HEADER_SIZE {
            return None;
        }
        let packet = ZCPacket::new_from_buf(BytesMut::from(message), ZCPacketType::DummyTunnel);
        let header = packet.peer_manager_header()?;
        if header.packet_type != PacketType::HandShake as u8 {
            return None;
        }
        let request = HandshakeRequest::decode(packet.payload()).ok()?;
        if request.network_name.is_empty() {
            return None;
        }
        Some(request.network_name)
    }

    /// Dials the loopback WebSocket listener of one network instance.
    ///
    /// The internal hop is always plain `ws://` because the instance listener is
    /// rewritten to `ws://127.0.0.1:<port>` by the core.
    async fn connect_loopback(port: u16) -> anyhow::Result<WebSocketStream<TcpStream>> {
        let authority = SocketAddr::from(([127, 0, 0, 1], port));
        let stream = tokio::time::timeout(INTERNAL_CONNECT_TIMEOUT, TcpStream::connect(authority))
            .await
            .map_err(|_| anyhow!("connect to {authority} timed out"))?
            .with_context(|| format!("connect to internal websocket listener at {authority}"))?;
        let _ = stream.set_nodelay(true);
        let uri: http::Uri = format!("ws://127.0.0.1:{port}/")
            .parse()
            .with_context(|| format!("build internal websocket uri for port {port}"))?;
        let builder = ClientBuilder::from_uri(uri).max_headers(128);
        let (websocket, _response) =
            tokio::time::timeout(INTERNAL_HANDSHAKE_TIMEOUT, builder.connect_on(stream))
                .await
                .map_err(|_| anyhow!("internal websocket handshake with {authority} timed out"))?
                .context("internal websocket handshake failed")?;
        Ok(websocket)
    }

    /// Forwards binary/text messages from `rx` to `tx` until either side ends,
    /// then closes `tx` to propagate the shutdown.
    async fn pump<C, U>(
        mut rx: SplitStream<WebSocketStream<C>>,
        mut tx: SplitSink<WebSocketStream<U>, Message>,
        network: &str,
    ) where
        C: AsyncRead + AsyncWrite + Unpin,
        U: AsyncRead + AsyncWrite + Unpin,
    {
        while let Some(item) = rx.next().await {
            let message = match item {
                Ok(message) => message,
                Err(err) => {
                    tracing::debug!(%network, ?err, "shared websocket relay receive failed");
                    break;
                }
            };
            let forward = if message.is_binary() {
                Message::binary(Bytes::from(message.into_payload()))
            } else if message.is_text() {
                Message::text(Bytes::from(message.into_payload()))
            } else if message.is_close() {
                break;
            } else {
                // Ping/pong frames are answered by tokio-websockets itself.
                continue;
            };
            if let Err(err) = tx.send(forward).await {
                tracing::debug!(%network, ?err, "shared websocket relay send failed");
                break;
            }
        }
        let _ = tx.close().await;
    }
}
